CREATE TABLE public.relatorios_acompanhamento (
    id_relatorio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id BIGINT NOT NULL,
    periodo_letivo VARCHAR(50),
    componente_curricular VARCHAR(150),
    docente VARCHAR(150),
    comentario_relacionamento TEXT,
    comentario_cognitivo TEXT,
    comentario_socioemocional TEXT,
    avancos_gerais TEXT,
    relato_dificuldades TEXT,
    fatores_externos TEXT,
    parecer TEXT,
    data_relatorio DATE,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_relatorio_aluno
    FOREIGN KEY (aluno_id)
    REFERENCES public.aluno(id_aluno)
    ON DELETE RESTRICT
);

CREATE TABLE public.relatorio_aspectos (
    id_aspecto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    relatorio_id BIGINT NOT NULL,
    grupo VARCHAR(30) NOT NULL,
    opcao VARCHAR(100) NOT NULL,
    descricao_outros TEXT,
    CONSTRAINT fk_aspecto_relatorio
    FOREIGN KEY (relatorio_id)
    REFERENCES public.relatorios_acompanhamento(id_relatorio)
    ON DELETE CASCADE,
    CONSTRAINT check_grupo_aspecto
    CHECK (grupo IN ('RELACIONAMENTO','COGNITIVO','SOCIOEMOCIONAL')),
    CONSTRAINT uk_relatorio_aspecto
    UNIQUE (relatorio_id, grupo, opcao)
);

CREATE TABLE public.relatorio_habilidades (
    id_habilidade BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    relatorio_id BIGINT NOT NULL,

    ordem INTEGER NOT NULL,
    habilidade_desenvolvida TEXT NOT NULL,
    nivel_aprendizado VARCHAR(20),
    observacoes TEXT,

    CONSTRAINT fk_habilidade_relatorio
    FOREIGN KEY (relatorio_id)
    REFERENCES public.relatorios_acompanhamento(id_relatorio)
    ON DELETE CASCADE,
    CONSTRAINT check_ordem_habilidade
    CHECK (ordem BETWEEN 1 AND 7),
    CONSTRAINT check_nivel_aprendizado
    CHECK (nivel_aprendizado IS NULL OR nivel_aprendizado IN ('SATISFATORIO', 'BOM', 'OTIMO')),
    CONSTRAINT uk_relatorio_habilidade_ordem
    UNIQUE (relatorio_id, ordem)

);

CREATE INDEX idx_relatorios_aluno
    ON public.relatorios_acompanhamento(aluno_id);

CREATE INDEX idx_aspectos_relatorio
    ON public.relatorio_aspectos(relatorio_id);

CREATE INDEX idx_habilidades_relatorio
    ON public.relatorio_habilidades(relatorio_id);
