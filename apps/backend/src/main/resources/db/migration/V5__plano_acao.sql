CREATE TABLE IF NOT EXISTS public.planos_acao (
    id_plano BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_id BIGINT NOT NULL,
    responsavel_nome VARCHAR(150),
    responsavel_parentesco VARCHAR(80),
    responsavel_contato VARCHAR(100),
    possui_comorbidades BOOLEAN NOT NULL DEFAULT FALSE,
    comorbidades TEXT,
    uso_medicacao_continua BOOLEAN NOT NULL DEFAULT FALSE,
    medicacao_continua TEXT,
    servicos_apoio TEXT,
    documentos_comprobatorios TEXT,
    necessidades_especificas TEXT NOT NULL,
    percurso_educacional TEXT NOT NULL,
    principais_demandas TEXT NOT NULL,
    propostas_intervencao TEXT NOT NULL,
    assinatura_coordenador VARCHAR(150) NOT NULL,
    data_documento DATE NOT NULL,
    autor VARCHAR(150) NOT NULL,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_plano_acao_aluno
        FOREIGN KEY (aluno_id)
        REFERENCES public.aluno(id_aluno)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_planos_acao_aluno ON public.planos_acao(aluno_id);
