CREATE TABLE public.aluno (
    id_aluno BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula VARCHAR(20) NOT NULL UNIQUE,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) UNIQUE,
    curso VARCHAR(100) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    data_cadastro DATE
);

CREATE TABLE public.atendimentos (
    id_atendimento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data VARCHAR(255) NOT NULL,
    hora VARCHAR(255) NOT NULL,
    observacoes TEXT,
    documento_url VARCHAR(255),
    profissional VARCHAR(255),
    aluno_id BIGINT NOT NULL,
        CONSTRAINT fk_atendimento_aluno
        FOREIGN KEY (aluno_id)
        REFERENCES public.aluno(id_aluno)
        ON DELETE RESTRICT
);

CREATE INDEX idx_atendimentos_aluno ON public.atendimentos(aluno_id);

CREATE TABLE public.usuarios (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    perfil VARCHAR(50) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    data_cadastro DATE NOT NULL
);